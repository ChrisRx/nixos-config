-- The compositor plugins and everything that only exists because they are
-- loaded: their hl.plugin.load() calls, the binds and gestures that call into
-- them, and their `plugin.*` config blocks. Split out of ./hyprland.lua, which
-- requires this file; the plugin-independent binds live in ./binds.lua.
--
-- Order matters inside this file and is the reason these cannot simply be
-- scattered: hl.plugin.gloview.* are real functions installed into that table
-- by the load call, so every bind and gesture naming one has to sit after it.
--
-- The .so paths are deliberately the fixed ~/.config/hypr/plugins/ entries
-- rather than store paths: this file is hand-edited and has no nix
-- interpolation, so ./home.nix links the built plugins there instead. Note that
-- directory is also what `require("plugins")` would fall back to as
-- plugins/init.lua if this file ever went missing, since package.path is
-- `<configdir>/?.lua;<configdir>/?/init.lua` and only the first pattern names
-- this file.
--
-- Loaded next to hyprland.lua in ~/.config/hypr, same as ./binds.lua; see that
-- file's header for how require resolves and what a reload re-runs.

-- The modifier ./binds.lua settled on, for the two gloview binds below. require
-- is cached, so this does not re-run that file.
