if enabled.kineticScroll then
  hl.plugin.load(os.getenv("HOME") .. "/.config/hypr/plugins/libhypr-kinetic-scroll.so")

  -- Scrolling stops dead the instant the fingers leave the pad, with no momentum
  -- from any source.
  --
  -- There are two sources, and only one of them is this plugin. Upstream is
  -- purely additive: it emits its own decaying scroll after a lift. The glide
  -- that outlives `enabled = 0` is the *client's* own kinetic scrolling — GTK,
  -- Chromium/Electron and Firefox each run their own deceleration, started by the
  -- wl_pointer.axis_stop event they get on lift. That is also why this is the
  -- right place to fix it rather than a per-app setting: a compositor plugin sits
  -- on the axis event before any client sees it.
  --
  -- `stop_on_lift` is not an upstream option; ./hypr-kinetic-scroll.nix patches it
  -- in. It cancels the one event per gesture that Hyprland turns into axis_stop
  -- (the zero-delta event libinput ends a two-finger scroll with) and drops the
  -- plugin's own decay, so neither half of the momentum survives the lift.
  --
  -- Vertical scrolling only. The first cut withheld axis_stop on both axes and
  -- broke two-finger horizontal swipes in browsers: back/forward is an overscroll
  -- gesture, committed or snapped back when the horizontal scroll sequence ends,
  -- so with no end event the swipe had nothing to resolve it. axis_stop is sent
  -- per axis and libinput only emits one for the axes that actually scrolled, so
  -- the horizontal event now passes through untouched.
  --
  -- Known trade-off: clients no longer see their *vertical* scroll sequences
  -- terminate. Nothing moves on its own as a result, but anything keyed on
  -- scroll-end rather than on scroll deltas — a GTK4 overshoot snapping back, say
  -- — stops being told when to run. `disabled_classes` below is the per-app
  -- escape hatch, and it is the same list the rest of the plugin honours.
  hl.config({
    plugin = {
      kinetic_scroll = {
        -- Writes every axis event and state transition to
        -- /tmp/hypr-kinetic-scroll.log — but *also* raises an on-screen
        -- notification every 200ms while scrolling, which is worth turning off
        -- before judging how any of this feels.
        -- debug = true,
        enabled = false,

        -- [false] the patched option. Note it needs `enabled` left on:
        -- everything the plugin does, including this, hangs off the axis
        -- callback that `enabled` gates.
        stop_on_lift = true,

        disable_in_browser = false,

        -- Exact window classes (comma or space separated) to leave entirely
        -- alone, scroll-end event included. Empty, for now: the browsers are
        -- already covered, since disable_in_browser defaults to 1 for the
        -- momentum half while stop_on_lift deliberately ignores it and kills
        -- their native glide too.
        disabled_classes = "",

        -- The momentum knobs below are inert while stop_on_lift is set, since
        -- beginDecay now bails before arming the decay timer. Kept, and kept
        -- documented, because they are what shapes the fling if stop_on_lift ever
        -- goes back to false — at which point these values give a short ~90-150ms
        -- flick rather than the ~430-570ms glide the defaults produce.
        --
        -- [0.92] per-frame velocity multiplier, applied every interval_ms (16).
        -- Coasting runs for ln(min_velocity/v)/ln(decel) frames, so lower stops
        -- sooner and the relationship is not gentle.
        decel = 0.82,

        -- [0.5] velocity below which no momentum is emitted at all. Raised well
        -- above the default: a deliberate slow scroll on this pad measures 0.5-0.9
        -- and the default would still fling it.
        min_velocity = 1.5,

        -- [1.25] impulse scale. The default hands the decay 25% more speed than
        -- the fingers had; 1.0 would continue the gesture at its own speed. Stacks
        -- with the input.touchpad.scroll_factor in ./hyprland.lua, which the
        -- plugin applies to its synthetic events too.
        delta_multiplier = 1.0,

        -- [true] cancel an in-flight fling when the pointer ends up over a different
        -- window or surface than the one the gesture started on — so momentum
        -- never spills into whatever the cursor happens to be sitting over by the
        -- time the decay catches up. The default, spelled out: like the knobs
        -- above it is inert while stop_on_lift is set (there is no decay left to
        -- cancel) and is here for the stop_on_lift = false path.
        stop_on_target_change = true,
      },
    },
  })
end

